#!/usr/bin/env node
/**
 * inspect-circuits.mjs — inspect the OFFICIAL zkVerify Agent Games circuits.
 *
 * Run:  node scripts/inspect-circuits.mjs
 *
 * For each published circuit (.zkey) this exports the verification key with
 * snarkjs and writes it to circuits/artifacts/<circuit>.vkey.json, then
 * prints: published vkHash (from circuit-info.json), protocol, curve, and
 * the number of public inputs (VK.IC.length - 1).
 *
 * LIMITATION (see SPEC.md): the platform publishes NO circuit source and NO
 * public-input name/order list. A .zkey's verification key exposes ONLY the
 * public-input COUNT. Input names and their order are TBD — this script
 * records the count in circuits/artifacts/INSPECT.md and does NOT guess
 * names. snarkjs also does not expose a vkHash recomputation, so the
 * published vkHash from circuit-info.json is quoted, not recomputed.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as snarkjs from "snarkjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const ART = process.env.CIRCUIT_DIR
  ? path.resolve(REPO_ROOT, process.env.CIRCUIT_DIR)
  : path.join(REPO_ROOT, "circuits", "artifacts");

const CIRCUITS = [
  { key: "gatekeeper", zkey: "gatekeeper_final.zkey", vkeyOut: "gatekeeper.vkey.json" },
  { key: "vfyPolicy", zkey: "vfy-policy_final.zkey", vkeyOut: "vfy-policy.vkey.json" },
];

function fail(msg) {
  console.error(`ERROR: ${msg}`);
  process.exit(1);
}

const infoPath = path.join(ART, "circuit-info.json");
if (!fs.existsSync(infoPath)) {
  fail(`circuit-info.json missing in ${ART} — run: bash scripts/download-artifacts.sh`);
}
const info = JSON.parse(fs.readFileSync(infoPath, "utf8"));

const rows = [];
for (const c of CIRCUITS) {
  const zkeyPath = path.join(ART, c.zkey);
  if (!fs.existsSync(zkeyPath)) {
    fail(`${c.zkey} missing in ${ART} — run: bash scripts/download-artifacts.sh`);
  }
  const vKey = await snarkjs.zKey.exportVerificationKey(zkeyPath);
  const vkeyPath = path.join(ART, c.vkeyOut);
  fs.writeFileSync(vkeyPath, JSON.stringify(vKey, null, 2) + "\n");

  const nPublic = vKey.IC.length - 1; // IC[0] is the constant term
  const row = {
    circuit: c.key,
    zkey: c.zkey,
    vkHashPublished: info.circuits?.[c.key]?.vkHash ?? "(not in circuit-info.json)",
    protocol: vKey.protocol,
    curve: vKey.curve,
    nPublicInputs: nPublic,
    nVars: vKey.nVars ?? null,
    vkeyFile: c.vkeyOut,
  };
  rows.push(row);

  console.log(`--- ${c.key} ---`);
  console.log(`  zkey:            ${c.zkey} (${fs.statSync(zkeyPath).size} bytes)`);
  console.log(`  vkey written:    ${c.vkeyOut}`);
  console.log(`  vkHash (published, from circuit-info.json): ${row.vkHashPublished}`);
  console.log(`  vkHash recompute: NOT available via snarkjs — published value quoted, not verified`);
  console.log(`  protocol:        ${row.protocol}`);
  console.log(`  curve:           ${row.curve}`);
  console.log(`  public inputs:   ${nPublic}  (VK.IC.length - 1 = ${vKey.IC.length} - 1)`);
  if (row.nVars !== null) console.log(`  nVars:           ${row.nVars}`);
  console.log(`  NOTE: input NAMES/order are NOT published — count only.`);
}

const md = `# Circuit inspection (generated by scripts/inspect-circuits.mjs)

Source: official zkVerify Agent Games artifacts — see SPEC.md and
https://agentgames.zkverify.io/api/circuit-info. These are the PLATFORM's
circuits, not ours; no local Circom build or trusted setup was run.

Generated: ${new Date().toISOString()}

| circuit | zkey | protocol | curve | public inputs (count) | published vkHash |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.circuit} | ${r.zkey} | ${r.protocol} | ${r.curve} | ${r.nPublicInputs} | \`${r.vkHashPublished}\` |`).join("\n")}

## What the VK tells us — and what it does not

- Each circuit's verification key (\`circuits/artifacts/*.vkey.json\`,
  exported with \`snarkjs zkey export verificationkey\`) exposes the
  **number of public inputs only** (\`VK.IC.length - 1\`).
- **Input NAMES and their ORDER are NOT published** anywhere readable
  (SPEC.md: TBD). They cannot be derived from the .zkey/.wasm alone.
  \`snarkjs.groth16.fullProve\` therefore cannot be called with correct
  inputs until the platform publishes the input list (or it is derived
  from the wasm's witness calculator, which embeds no names either).
- **vkHash is NOT recomputed here.** snarkjs exposes no vkHash function and
  the platform's hashing scheme for the VK is unpublished, so the published
  vkHash from \`circuit-info.json\` is quoted verbatim. Treat it as the
  platform's registered identifier (used as \`circuitVersion\` when
  submitting proofs via Kurier), not as a locally verified digest.
- Curves/protocols above come straight from the exported VKs.

## Verification keys on disk

${rows.map((r) => `- \`${r.vkeyFile}\` — ${r.circuit} VK (protocol ${r.protocol}, curve ${r.curve}, ${r.nPublicInputs} public inputs)`).join("\n")}

## Input-signal-name recovery (see circuits/artifacts/PROBE.md)

Method: the wasm stores input signals by FNV-1a hash of the NAME only
(circom_runtime \`_doCalculateWitness\`), so names were recovered by
probing candidates from SPEC.md with scripts/probe-input-names.mjs —
a name counts as FOUND only when a witness attempt gets past the
per-signal check. \`strings\` on both wasms finds no signal names at all
(only template/function names: main templates \`GatekeeperEvaluation_79\`
and \`VfyPolicyProof_154\`, both using Poseidon internally).

- **gatekeeper: 13/13 COMPLETE** — \`registeredVkHash, proofVkHash,
  minimum, publicBalance, expiryBlock, currentBlock, recipient,
  conditionRecipient, amount, maxTransfer, decision, taskId, salt\`.
  Verified by a live fullProve + groth16.verify round-trip (see
  PROVING.md for the public-signal order and decision encoding).
- **vfyPolicy: 9/17 INCOMPLETE** — known: \`commitment, matchId,
  turnNumber, selfBalance, opponentBalance, action, amount,
  circuitVersion, salt\`. The remaining 8 private input names are NOT
  published anywhere readable and were NOT guessed.
`;

fs.writeFileSync(path.join(ART, "INSPECT.md"), md);
console.log(`\nWrote ${path.join(ART, "INSPECT.md")}`);

// NOTE: importing snarkjs (ESM import of its CJS bundle) leaves the event
// loop alive after the script finishes — exit explicitly.
process.exit(0);
