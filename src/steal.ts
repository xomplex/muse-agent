/**
 * Steal the VFY — 20-turn state machine.
 *
 * Shapes are verbatim from SPEC.md (authoritative, read 2026-11-15).
 *
 * Turn envelope:
 *   {"protocolVersion":"v1","eventId":"steal-the-vfy","mode":"competition",
 *    "matchId":"...","turn":3,"issuedAt":"...","deadlineAt":"...",
 *    "state":{"selfBalance":"95","opponentBalance":"105",
 *     "selfFortifiedUntilTurn":null,"opponentFortifiedUntilTurn":null},
 *    "strategyCommitment":{"hash":"0x..."},"resolverVersion":"v1","nonce":"..."}
 * Response:
 *   {"matchId":"...","turn":3,"action":{"type":"EXTRACT","amount":5},
 *    "policyProof":{"circuitVersion":"v1","proofReference":"0x...",
 *     "publicInputsHash":"0x..."},"agentTimestamp":"...",
 *    "idempotencyKey":"..."}
 *
 * Actions: HOLD (steals 0), FORTIFY (costs 2 VFY, blocks up to 6 incoming
 * extraction that turn), EXTRACT N (steals up to N, max 10).
 * `action.amount` must be OMITTED entirely for HOLD/FORTIFY — the platform
 * schema rejects it even as 0. For EXTRACT it is a NUMBER.
 *
 * FORTIFICATION semantics (documented assumption — the guide says only
 * "blocks up to 6 incoming extraction that turn"): a fortification active
 * on a turn blocks the first 6 of any incoming EXTRACT that turn, so an
 * EXTRACT N against a fortified opponent steals max(0, N-6). A
 * `*FortifiedUntilTurn` value means "fortified through that turn
 * (inclusive)".
 *
 * POLICY (deterministic, documented here — the strategy fingerprint /
 * commitment hash is frozen once play starts):
 * - EXTRACT when ahead-or-even AND the opponent is NOT fortified this
 *   turn: steal a bounded fraction of the exposed balance,
 *   min(10, max(1, floor(opponent * 0.10))), capped by the opponent's
 *   balance. Never extract against a fortified opponent (up to 6 of the
 *   take would be blocked, so the move is poor value).
 * - FORTIFY when behind (opponent > me) and we can afford the 2-VFY cost
 *   while keeping a positive balance (me > 2): the opponent is likely to
 *   extract while ahead, and fortifying blocks up to 6 of that take.
 * - HOLD otherwise, and on ANY validation failure (fail closed).
 *
 * This module is PURE: it models the game mechanics as the agent sees
 * them from the turn envelopes. The platform is the authority on the real
 * balances (the envelope carries them as decimal strings); applyMove only
 * updates local state from the declared action, and validateTurn refuses
 * to advance when the envelope balances disagree with local state, so a
 * desync never silently compounds.
 *
 * Move effects (local model — the platform's resolution is authoritative):
 * - EXTRACT amount n: stolen = min(n, opponent), or max(0, n-6) capped by
 *   opponent when the opponent is fortified this turn; me += stolen,
 *   opponent -= stolen.
 * - FORTIFY cost 2: me -= 2; selfFortifiedUntilTurn = this turn.
 * - HOLD: no change.
 *
 * Idempotency: the inbound `nonce` is the replay guard (one use per
 * match); the outbound `idempotencyKey` is generated by the server as
 * `${matchId}:${turn}:${uuid}` and never repeats across turns.
 */
import type { StealAction, StealEnvelope } from "./types";

export const ACTION_EXTRACT = "EXTRACT" as const;
export const ACTION_FORTIFY = "FORTIFY" as const;
export const ACTION_HOLD = "HOLD" as const;

export const TOTAL_TURNS = 20;
export const STARTING_BALANCE = 100;
/** Fixed FORTIFY cost in VFY (SPEC.md). */
export const FORTIFY_COST = 2;
/** How much incoming extraction a fortification blocks (SPEC.md: up to 6). */
export const FORTIFY_BLOCK = 6;
/** EXTRACT amount cap (SPEC.md: max 10). */
export const EXTRACT_MAX = 10;

export interface Move {
  turn: number;
  action: StealAction;
  /** Inbound envelope nonce (replay guard). */
  nonce: string;
  /** Outbound idempotencyKey sent in the response. */
  idempotencyKey: string;
}

export interface MatchState {
  matchId: string;
  /** Next expected turn, 0..19 while playing; 20 when the match is done. */
  turn: number;
  me: number;
  opponent: number;
  selfFortifiedUntilTurn: number | null;
  opponentFortifiedUntilTurn: number | null;
  history: Move[];
  /** Inbound nonces already used in this match (replay guard). */
  usedNonces: Set<string>;
  /** Hash of the committed strategy (registered with the platform). */
  policyCommitment: string;
}

export function createMatch(
  matchId: string,
  policyCommitment: string,
): MatchState {
  return {
    matchId,
    turn: 0,
    me: STARTING_BALANCE,
    opponent: STARTING_BALANCE,
    selfFortifiedUntilTurn: null,
    opponentFortifiedUntilTurn: null,
    history: [],
    usedNonces: new Set<string>(),
    policyCommitment,
  };
}

/** True once all 20 turns have been played. */
export function isMatchComplete(state: MatchState): boolean {
  return state.turn >= TOTAL_TURNS;
}

/**
 * Is a fortification active on the given turn? `fortifiedUntilTurn` is
 * inclusive: fortified through that turn.
 */
export function isFortifiedOnTurn(
  fortifiedUntilTurn: number | null | undefined,
  turn: number,
): boolean {
  return (
    typeof fortifiedUntilTurn === "number" && turn <= fortifiedUntilTurn
  );
}

/** Parse a decimal-string balance from the envelope; null if invalid. */
export function parseBalance(value: unknown): number | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  if (!/^-?\d+$/.test(trimmed)) return null;
  const n = Number(trimmed);
  return Number.isSafeInteger(n) ? n : null;
}

/**
 * Sync the platform-authoritative fortification fields from an envelope
 * into a copy of the state. Balances are NOT synced here — they are
 * validated by validateTurn (a mismatch fails the turn instead).
 */
export function syncFortification(
  state: MatchState,
  selfFortifiedUntilTurn: number | null,
  opponentFortifiedUntilTurn: number | null,
): MatchState {
  return { ...state, selfFortifiedUntilTurn, opponentFortifiedUntilTurn };
}

/**
 * Deterministic policy move for the current state. Pure — no I/O, no
 * randomness — so the same state always yields the same move, which is
 * what the registered strategy commitment covers.
 */
export function policyMove(state: MatchState): StealAction {
  if (isMatchComplete(state)) return { type: ACTION_HOLD };

  const { me, opponent, turn } = state;
  const opponentFortified = isFortifiedOnTurn(
    state.opponentFortifiedUntilTurn,
    turn,
  );

  if (me >= opponent && !opponentFortified) {
    // Ahead-or-even, opponent exposed: extract a bounded fraction.
    const amount = Math.min(
      EXTRACT_MAX,
      Math.max(1, Math.floor(opponent * 0.1)),
      opponent,
    );
    if (amount > 0) return { type: ACTION_EXTRACT, amount };
    return { type: ACTION_HOLD };
  }

  if (opponent > me && me > FORTIFY_COST) {
    // Behind and the opponent (ahead) is likely to extract: fortify.
    return { type: ACTION_FORTIFY };
  }

  return { type: ACTION_HOLD };
}

export type ValidateTurnResult =
  | { ok: true }
  | { ok: false; reason: string };

/**
 * Validate an incoming turn envelope against local match state.
 * Fail closed: any mismatch means the turn must NOT advance — the
 * server answers HOLD for that turn instead.
 */
export function validateTurn(
  envelope: StealEnvelope,
  state: MatchState,
): ValidateTurnResult {
  if (envelope.matchId !== state.matchId) {
    return { ok: false, reason: "matchId mismatch" };
  }
  if (isMatchComplete(state)) {
    return { ok: false, reason: "match complete" };
  }
  if (envelope.turn !== state.turn) {
    return {
      ok: false,
      reason: `stale turn: expected ${state.turn}, got ${envelope.turn}`,
    };
  }
  if (typeof envelope.nonce !== "string" || envelope.nonce.length === 0) {
    return { ok: false, reason: "missing nonce" };
  }
  if (state.usedNonces.has(envelope.nonce)) {
    return { ok: false, reason: "nonce already used" };
  }
  const commitmentHash = envelope.strategyCommitment?.hash;
  if (
    typeof commitmentHash === "string" &&
    commitmentHash.length > 0 &&
    commitmentHash !== state.policyCommitment
  ) {
    return {
      ok: false,
      reason: "strategyCommitment hash mismatch",
    };
  }
  if (!envelope.state || typeof envelope.state !== "object") {
    return { ok: false, reason: "missing or invalid state" };
  }
  const me = parseBalance(envelope.state.selfBalance);
  const opponent = parseBalance(envelope.state.opponentBalance);
  if (me === null || opponent === null) {
    return { ok: false, reason: "missing or invalid balances" };
  }
  if (me !== state.me || opponent !== state.opponent) {
    return {
      ok: false,
      reason:
        `balances mismatch: envelope self=${me} opponent=${opponent}, ` +
        `state me=${state.me} opponent=${state.opponent}`,
    };
  }
  return { ok: true };
}

export type ApplyMoveResult =
  | { ok: true; state: MatchState }
  | { ok: false; reason: string };

/**
 * Apply a move to a match, returning a NEW state object (the input is
 * not mutated; the new state's usedNonces is a fresh Set copied from
 * the old one plus the new nonce).
 *
 * Enforces the platform schema rule: action.amount must be OMITTED for
 * HOLD/FORTIFY — providing it (even as 0) is rejected. For EXTRACT the
 * amount is a number, 1..10.
 */
export function applyMove(
  state: MatchState,
  action: StealAction,
  nonce: string,
  idempotencyKey: string,
): ApplyMoveResult {
  if (isMatchComplete(state)) {
    return { ok: false, reason: "match complete" };
  }
  if (state.usedNonces.has(nonce)) {
    return { ok: false, reason: "nonce already used" };
  }
  if (action.type === ACTION_HOLD || action.type === ACTION_FORTIFY) {
    if (action.amount !== undefined) {
      return {
        ok: false,
        reason: `${action.type} must not carry an amount`,
      };
    }
  }
  if (action.type === ACTION_EXTRACT) {
    if (
      typeof action.amount !== "number" ||
      !Number.isInteger(action.amount) ||
      action.amount <= 0 ||
      action.amount > EXTRACT_MAX
    ) {
      return { ok: false, reason: "invalid EXTRACT amount" };
    }
  }

  let me = state.me;
  let opponent = state.opponent;
  let selfFortifiedUntilTurn = state.selfFortifiedUntilTurn;
  if (action.type === ACTION_EXTRACT) {
    const amount = action.amount as number;
    let steal = Math.min(amount, opponent);
    if (isFortifiedOnTurn(state.opponentFortifiedUntilTurn, state.turn)) {
      // Fortification blocks up to 6 of this turn's incoming extraction.
      steal = Math.max(0, Math.min(amount - FORTIFY_BLOCK, opponent));
    }
    me += steal;
    opponent -= steal;
  } else if (action.type === ACTION_FORTIFY) {
    if (me <= FORTIFY_COST) {
      return { ok: false, reason: "cannot afford FORTIFY" };
    }
    me -= FORTIFY_COST;
    selfFortifiedUntilTurn = state.turn;
  }

  const usedNonces = new Set(state.usedNonces);
  usedNonces.add(nonce);
  const next: MatchState = {
    ...state,
    turn: state.turn + 1,
    me,
    opponent,
    selfFortifiedUntilTurn,
    history: [
      ...state.history,
      { turn: state.turn, action: { ...action }, nonce, idempotencyKey },
    ],
    usedNonces,
  };
  return { ok: true, state: next };
}
